function storedLang(): Lang | null {
  try {
    const value = localStorage.getItem(LANG_STORAGE);
    return value === 'en' || value === 'ja' ? value : null;
  } catch { return null; }
}

let current: Lang = storedLang() ?? (typeof window === 'undefined' ? 'en' : 'ja');

/** The language the UI is currently shown in. */
export function getLang(): Lang {
  return current;
}

/** Look up a UI string in the current language, filling `{name}` placeholders. */
export function t(key: string, params: Record<string, string | number> = {}): string {
  const template = DICT[current][key] ?? DICT.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match);
}

/** A song's title in the current language: its Japanese form when the UI is Japanese and one is known. */
export function displayTitle(entry: { title: string; titleJa?: string }): string {
  return current === 'ja' && entry.titleJa ? entry.titleJa : entry.title;
}

/** A song's subtitle in the current language: its Japanese form when the UI is Japanese and one is known. */
export function displaySubtitle(entry: { subtitle: string; subtitleJa?: string }): string {
  return current === 'ja' && entry.subtitleJa ? entry.subtitleJa : entry.subtitle;
}

/**
 * Switch the UI language: persist the choice, set the document language,
 * rewrite the static markup and let dynamic views re-render via the event.
 */
export function applyLanguage(lang: Lang): void {
  current = lang;
  try { localStorage.setItem(LANG_STORAGE, lang); } catch { /* storage unavailable: session-only */ }
  document.documentElement.lang = lang;
  for (const element of document.querySelectorAll<HTMLElement>('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n!);
  }
  for (const element of document.querySelectorAll<HTMLElement>('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder!));
  }
  for (const element of document.querySelectorAll<HTMLElement>('[data-i18n-aria]')) {
    element.setAttribute('aria-label', t(element.dataset.i18nAria!));
  }
  for (const element of document.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    element.setAttribute('title', t(element.dataset.i18nTitle!));
  }
  const select = document.querySelector<HTMLSelectElement>('#lang-select');
  if (select) select.value = lang;
  window.dispatchEvent(new CustomEvent('languagechange', { detail: lang }));
}

/** Wire the header language selector and apply the stored (or default) language. Runs once at startup. */
export function initI18n(): void {
  const select = document.querySelector<HTMLSelectElement>('#lang-select');
  select?.addEventListener('change', () => applyLanguage(select.value === 'en' ? 'en' : 'ja'));
  applyLanguage(current);
}
